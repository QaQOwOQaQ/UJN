#include<iostream>
#include<cstring>
#include<algorithm>
#include<cmath>
#include<stdlib.h>
#define ll long long

using namespace std;

const ll mod = 10e9+7;
int main()
{
	int n,m;
	ll ans;
	while(scanf("%d%d",&n,&m)!=EOF)
	{
		ans = 0;
		for(int i=0;i<m;i++)
		{
			int l,r;
			cin >> l >> r;
		}
		
		cout << ans%mod << endl;		
	}


	return 0;
	
 } 
